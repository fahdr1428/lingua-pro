/** Pick a fun fact for a language, avoiding ones recently shown if possible. */
export function pickFunFact(langCode, recentlySeenIds = []) {
  const list = FUN_FACTS[langCode];
  if (!list || list.length === 0) return null;
  // recentlySeenIds is an array of indices (we key by index since facts are
  // identified by their position in the array — simple and stable).
  const unseen = list
    .map((_, i) => i)
    .filter((i) => !recentlySeenIds.includes(i));
  const pool = unseen.length > 0 ? unseen : list.map((_, i) => i);
  const idx = pool[Math.floor(Math.random() * pool.length)];
  return { fact: list[idx], idx };
}
