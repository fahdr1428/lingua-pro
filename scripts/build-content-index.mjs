// =============================================================================
// build-content-index.mjs (v103) — generate src/data/contentIndex.js.
//
// The home screen asks two questions that are pure availability:
//
//     getConversations(pack.code).length > 0 || (PASSAGES[pack.code] || []).length > 0
//
// Answering them statically imported conversations.js (75KB of source) and
// passages.js (29KB) into the EAGER bundle — the one every learner downloads
// before the first word appears — for two `.length` checks. The screens that
// actually show that content, Conversations and Reading, are both lazy, so the
// only thing keeping it in the first payload was the question "is there any?".
//
// So the answer gets extracted into a table of numbers. Generated rather than
// hand-kept, because a hand-kept index is a copy, and every copy in this
// repo's history has drifted — that is the v92 bug and the v102 one.
// validate-content-index.mjs regenerates it and fails the build if it differs.
//
//   npm run build-content-index
// =============================================================================

import { writeFileSync } from "node:fs";
import { CONVERSATIONS } from "../src/data/conversations.js";
import { PASSAGES } from "../src/data/passages.js";
import { LANGUAGES } from "../src/data/registry.js";

export function buildIndex() {
  const conversations = {};
  const passages = {};
  for (const code of Object.keys(LANGUAGES).sort()) {
    const c = CONVERSATIONS[code];
    const p = PASSAGES[code];
    conversations[code] = Array.isArray(c) ? c.length : 0;
    passages[code] = Array.isArray(p) ? p.length : 0;
  }
  return { conversations, passages };
}

export function render({ conversations, passages }) {
  const table = (obj) =>
    Object.entries(obj).map(([k, v]) => `  ${k}: ${v},`).join("\n");

  return `// =============================================================================
// contentIndex.js — GENERATED by scripts/build-content-index.mjs. Do not edit.
//
// How much of each kind of content a language has, and nothing else. The home
// screen needs to know whether there is anything behind a door before it offers
// it; it does not need the content itself, and importing 104KB of source to
// answer "is there any?" put both libraries in the bundle every learner
// downloads before their first word.
//
// Regenerate with:  npm run build-content-index
// Kept honest by:   npm run validate-content-index  (runs in npm run check)
// =============================================================================

export const CONVERSATION_COUNT = {
${table(conversations)}
};

export const PASSAGE_COUNT = {
${table(passages)}
};

export const hasConversations = (code) => (CONVERSATION_COUNT[code] || 0) > 0;
export const hasPassages = (code) => (PASSAGE_COUNT[code] || 0) > 0;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const index = buildIndex();
  writeFileSync("src/data/contentIndex.js", render(index));
  const langs = Object.keys(index.conversations).length;
  const conv = Object.values(index.conversations).reduce((a, b) => a + b, 0);
  const pass = Object.values(index.passages).reduce((a, b) => a + b, 0);
  console.log(`\n  src/data/contentIndex.js — ${langs} languages · ${conv} conversations · ${pass} passages\n`);
}
