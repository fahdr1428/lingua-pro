// =============================================================================
// build-audio-index.mjs (v107) — generate src/data/audioIndex.js: which words
// have a recorded MP3 in public/audio, as id ranges per language.
//
// tts.js used to find out by asking: every speak() with an audioId fetched
// /audio/{lang}/{id}.mp3 and fell back to browser speech when it 404'd. Eleven
// languages ship recordings for their first 66–157 words; the other 3,000-odd
// words — including every word added since — each cost a request that could
// only fail, a red "Failed to load resource" in the console, and a network
// round trip of silence before the fallback voice started. On a phone on a
// slow connection that silence is the gap between tapping 🔊 and hearing
// anything.
//
// Generated rather than hand-kept, like contentIndex.js, because a copy
// drifts: validate-audio-index regenerates it and fails `check` if it differs,
// so adding recordings without re-running this is caught.
//
//   npm run build-audio-index      (after scripts/generate-audio.cjs)
// =============================================================================

import { readdirSync, existsSync, writeFileSync, statSync } from "node:fs";

const ROOT = "public/audio";

/** { code: [[from, to], ...] } — inclusive runs of the numeric part of the id. */
export function buildAudioIndex() {
  const out = {};
  if (!existsSync(ROOT)) return out;
  for (const code of readdirSync(ROOT).sort()) {
    if (!statSync(`${ROOT}/${code}`).isDirectory()) continue; // .gitkeep and friends
    const nums = readdirSync(`${ROOT}/${code}`)
      .map((f) => f.match(new RegExp(`^${code}_(\\d+)\\.mp3$`)))
      .filter(Boolean)
      .map((m) => Number(m[1]))
      .sort((a, b) => a - b);
    if (!nums.length) continue;
    const runs = [];
    for (const n of nums) {
      const last = runs[runs.length - 1];
      if (last && n === last[1] + 1) last[1] = n;
      else runs.push([n, n]);
    }
    out[code] = runs;
  }
  return out;
}

export function render(index) {
  const lines = Object.entries(index).map(([code, runs]) => `  ${JSON.stringify(code)}: ${JSON.stringify(runs)},`);
  return `// GENERATED by scripts/build-audio-index.mjs — do not edit by hand.
// Which vocabulary ids have a recorded MP3 in public/audio, as inclusive
// [from, to] runs of the id's number. validate-audio-index fails the build if
// this is out of date with the files.
export const AUDIO_RUNS = {
${lines.join("\n")}
};

/** Is there a recording for this word? No network request involved. */
export function hasRecording(code, id) {
  const runs = AUDIO_RUNS[code];
  if (!runs || !id) return false;
  const m = String(id).match(/_(\\d+)$/);
  if (!m || !String(id).startsWith(code + "_")) return false;
  const n = Number(m[1]);
  return runs.some(([a, b]) => n >= a && n <= b);
}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const index = buildAudioIndex();
  writeFileSync("src/data/audioIndex.js", render(index));
  const total = Object.values(index).flat().reduce((n, [a, b]) => n + b - a + 1, 0);
  console.log(`  audioIndex.js: ${total} recordings across ${Object.keys(index).length} languages`);
}
