const css = readFileSync("src/index.css", "utf8");

const pick = (name) => {
  const m = css.match(new RegExp(`^\\s*${name}:\\s*([^;]+);`, "m"));
  return m ? m[1].trim() : null;
};

// Tokens grouped the way someone building a screen actually reaches for them,
