const GROUPS = {
  "Ground & surfaces": ["--bg", "--bg-alt", "--surface", "--surface-hi", "--glass", "--raised", "--raised-soft", "--border"],
  "Text": ["--text", "--text-dim", "--text-mute", "--accent-text", "--primary-text", "--danger-text"],
  "Primary action": ["--primary", "--on-primary", "--primary-dark", "--on-primary-dark", "--primary-soft"],
  "Solid / inverted": ["--ink", "--ink-solid", "--ink-on"],
  "Semantic": ["--accent", "--accent-soft", "--danger", "--miss", "--on-miss", "--root"],
  "Data & decoration": ["--blue", "--purple", "--pink"],
};

const themeKeys = Object.keys(THEMES);
const rows = (names) =>
  names
    .filter((n) => THEMES[themeKeys[0]].vars[n])
    .map((n) => `| \`${n}\` | ${themeKeys.map((k) => `\`${THEMES[k].vars[n]}\``).join(" | ")} |`)
    .join("\n");

const colourTables = Object.entries(GROUPS)
  .map(([title, names]) => {
    const body = rows(names);
    if (!body) return "";
    return `#### ${title}\n\n| Token | ${themeKeys.join(" | ")} |\n|---|${themeKeys.map(() => "---").join("|")}|\n${body}\n`;
  })
  .filter(Boolean)
  .join("\n");

// Anything defined in a theme but not placed in a group above — so a new token
// cannot be added without appearing here.
const grouped = new Set(Object.values(GROUPS).flat());
const ungrouped = Object.keys(THEMES[themeKeys[0]].vars).filter((k) => !grouped.has(k));

